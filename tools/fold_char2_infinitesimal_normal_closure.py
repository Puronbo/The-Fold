#!/usr/bin/env python3
"""Exact GF(2) verification of UF-039. Uses only the Python standard library."""
# Monomials x^i z^j, 0<=i<=3, 0<=j<=1 are encoded by i*2+j.
MONS=[(i,j) for i in range(4) for j in range(2)]
INDEX={m:i for i,m in enumerate(MONS)}


def add_poly(a,b):
    return a ^ b


def mul_poly(a,b):
    out=0
    for i,(ix,iz) in enumerate(MONS):
        if not (a>>i)&1: continue
        for j,(jx,jz) in enumerate(MONS):
            if (b>>j)&1 and ix+jx<4 and iz+jz<2:
                out ^= 1 << INDEX[(ix+jx,iz+jz)]
    return out


def deriv_poly(f,var):
    out=0
    for k,(i,j) in enumerate(MONS):
        if not ((f>>k)&1): continue
        if var==0 and i%2:
            out ^= 1 << INDEX[(i-1,j)]
        if var==1 and j%2:
            out ^= 1 << INDEX[(i,j-1)]
    return out


def apply(D,f):
    P,Q=D
    return mul_poly(deriv_poly(f,0),P) ^ mul_poly(deriv_poly(f,1),Q)


def bracket(D,E):
    return (apply(D,E[0]) ^ apply(E,D[0]),
            apply(D,E[1]) ^ apply(E,D[1]))


def vec(D):
    return D[0] | (D[1]<<8)


def from_vec(v):
    return (v&255,(v>>8)&255)


def rank_gf2(vectors):
    pivots={}
    for v in vectors:
        w=v
        while w:
            p=w.bit_length()-1
            if p in pivots:
                w ^= pivots[p]
            else:
                pivots[p]=w
                break
    return len(pivots)


def in_span(v, vectors):
    return rank_gf2(vectors+[v])==rank_gf2(vectors)


def mon(i,j):
    return 1 << INDEX[(i,j)]


ZERO=0
ONE=mon(0,0)
X=mon(1,0)
X2=mon(2,0)
X3=mon(3,0)
Z=mon(0,1)
XZ=mon(1,1)
X2Z=mon(2,1)
X3Z=mon(3,1)

# Seven tangent generators of U, with I=B+G in characteristic two.
delta_A=(X2,XZ)
delta_B=(X3,X2Z)
delta_C=(XZ,ZERO)
delta_D=(X2Z,ZERO)
delta_E=(X3Z,ZERO)
delta_G=(ZERO,X3^X2Z)
delta_J=(ZERO,X3Z)
U=[delta_A,delta_B,delta_C,delta_D,delta_E,delta_G,delta_J]

# Full derivation basis: every monomial times either partial derivative.
FULL=[(1<<i,0) for i in range(8)]+[(0,1<<i) for i in range(8)]

# Reduced Lie algebra: m^2 partial_x + m^2 partial_z, plus
# x partial_x, z partial_x, z partial_z (the Lie algebra of B).
M2=[mon(i,j) for i,j in MONS if i+j>=2]
RED=[(m,0) for m in M2]+[(0,m) for m in M2]+[(X,0),(Z,0),(0,Z)]


def lie_ideal_span(generators, ambient):
    span=[vec(d) for d in generators]
    while True:
        before=rank_gf2(span)
        additions=[]
        for sv in list(span):
            d=from_vec(sv)
            for e in ambient:
                w=vec(bracket(e,d))
                if w and not in_span(w,span+additions):
                    additions.append(w)
        span.extend(additions)
        if rank_gf2(span)==before:
            return rank_gf2(span)


def main():
    ex=(ONE,ZERO)
    ez=(ZERO,ONE)
    assert bracket(ex,delta_A)==(ZERO,Z)
    assert bracket(ez,delta_A)==(ZERO,X)
    assert bracket(ex,delta_B)==(X2,ZERO)
    assert bracket(ez,delta_B)==(ZERO,X2)
    assert bracket(ex,delta_C)==(Z,ZERO)
    assert bracket(ez,delta_C)==(X,ZERO)
    assert bracket(ez,(ZERO,Z))==(ZERO,ONE)
    assert bracket(ez,(Z,ZERO))==(ONE,ZERO)

    full_rank=lie_ideal_span(U,FULL)
    reduced_rank=lie_ideal_span(U,RED)
    assert full_rank==16, full_rank
    assert reduced_rank==8, reduced_rank

    print("UF-039 exact GF(2) checks: PASS")
    print("Lie ideal generated by Lie(U) in Der(C): dimension 16")
    print("Lie ideal generated using Lie(Aut(C)_red): dimension 8")
    print("The latter agrees with Lie(N); the former fills the full tangent space.")


if __name__=="__main__":
    main()
