#!/usr/bin/env python3
"""UF-003: minimal geometric Fold generators from crease-axis catalogues.

A reflection axis j modulo m is sigma_j(z) = zeta_m**j * conjugate(z).
Two reflections compose to a rotation. This geometric model is separate from
the arithmetic Frobenius-power transitions used by UFSF/UF-002.

Standard library only.
"""
from __future__ import annotations

from itertools import combinations
from math import gcd
from typing import Iterable, Optional

GroupElement = tuple[int, int]  # (reflection parity, rotation index)


def prime_factors(n: int) -> tuple[int, ...]:
    if n < 1:
        raise ValueError("n must be positive")
    out: list[int] = []
    p = 2
    while p * p <= n:
        if n % p == 0:
            out.append(p)
            while n % p == 0:
                n //= p
        p = 3 if p == 2 else p + 2
    if n > 1:
        out.append(n)
    return tuple(out)


def normalize_axes(m: int, axes: Iterable[int]) -> tuple[int, ...]:
    if m < 1:
        raise ValueError("m must be positive")
    return tuple(sorted({a % m for a in axes}))


def compose(m: int, left: GroupElement, right: GroupElement) -> GroupElement:
    """Return left after right for z -> zeta^b * (z or conjugate(z))."""
    e, b = left
    f, c = right
    return (e ^ f, (b + (-1 if e else 1) * c) % m)


def reflection(axis: int, m: int) -> GroupElement:
    return (1, axis % m)


def generated_elements(m: int, axes: Iterable[int]) -> frozenset[GroupElement]:
    """Enumerate the subgroup generated by the selected reflections."""
    generators = tuple(reflection(a, m) for a in normalize_axes(m, axes))
    identity: GroupElement = (0, 0)
    seen = {identity}
    frontier = [identity]
    while frontier:
        x = frontier.pop()
        for g in generators:
            for y in (compose(m, g, x), compose(m, x, g)):
                if y not in seen:
                    seen.add(y)
                    frontier.append(y)
    return frozenset(seen)


def rotation_subgroup_order(m: int, axes: Iterable[int]) -> int:
    """Order of the rotation subgroup generated by a nonempty axis set."""
    if m < 1:
        raise ValueError("m must be positive")
    J = normalize_axes(m, axes)
    if not J:
        return 1
    anchor = J[0]
    g = m
    for j in J[1:]:
        g = gcd(g, (j - anchor) % m)
    return m // g


def generated_dihedral_group_order(m: int, axes: Iterable[int]) -> int:
    J = normalize_axes(m, axes)
    return 1 if not J else 2 * rotation_subgroup_order(m, J)


def _minimum_for_anchor(
    m: int, axes: tuple[int, ...], target_q: int, anchor: int
) -> Optional[tuple[int, ...]]:
    """Set-cover DP for one anchor crease."""
    g = m // target_q
    primes = prime_factors(target_q)
    bit = {p: 1 << i for i, p in enumerate(primes)}
    full = (1 << len(primes)) - 1
    candidates: list[tuple[int, int]] = []

    for b in axes:
        if b == anchor:
            continue
        delta = (b - anchor) % m
        if delta % g:
            continue
        normalized_delta = (delta // g) % target_q
        cover = 0
        for p in primes:
            if normalized_delta % p:
                cover |= bit[p]
        if cover:
            candidates.append((b, cover))

    dp: dict[int, tuple[int, ...]] = {0: ()}
    for b, cover in candidates:
        updated = dict(dp)
        for old_mask, chosen in dp.items():
            new_mask = old_mask | cover
            proposal = chosen + (b,)
            previous = updated.get(new_mask)
            if previous is None or (len(proposal), proposal) < (len(previous), previous):
                updated[new_mask] = proposal
        dp = updated

    if full not in dp:
        return None
    return tuple(sorted((anchor,) + dp[full]))


def minimum_axes(
    m: int, allowed_axes: Iterable[int], target_rotation_order: int
) -> Optional[tuple[int, ...]]:
    """Find a minimum crease subset generating a dihedral subgroup D_q, q|m."""
    if m < 1 or target_rotation_order < 1 or m % target_rotation_order:
        raise ValueError("target rotation order must be a positive divisor of m")
    axes = normalize_axes(m, allowed_axes)
    if not axes:
        return None

    best: Optional[tuple[int, ...]] = None
    for anchor in axes:
        candidate = _minimum_for_anchor(m, axes, target_rotation_order, anchor)
        if candidate is None:
            continue
        if rotation_subgroup_order(m, candidate) != target_rotation_order:
            raise AssertionError("DP candidate failed gcd verification")
        if best is None or (len(candidate), candidate) < (len(best), best):
            best = candidate
    return best


def brute_force_minimum_axes(
    m: int, allowed_axes: Iterable[int], target_rotation_order: int
) -> Optional[tuple[int, ...]]:
    axes = normalize_axes(m, allowed_axes)
    for size in range(1, len(axes) + 1):
        for chosen in combinations(axes, size):
            if rotation_subgroup_order(m, chosen) == target_rotation_order:
                return chosen
    return None


def verify(max_m: int = 9) -> dict[str, int]:
    composition_checks = subgroup_checks = dp_checks = examples = 0
    for m in range(2, max_m + 1):
        elements = [(e, b) for e in (0, 1) for b in range(m)]
        for left in elements:
            for right in elements:
                assert compose(m, left, right) in elements
                composition_checks += 1

        for mask in range(1 << m):
            axes = tuple(j for j in range(m) if mask & (1 << j))
            assert len(generated_elements(m, axes)) == generated_dihedral_group_order(m, axes)
            subgroup_checks += 1
            if not axes:
                continue
            for q in range(1, m + 1):
                if m % q:
                    continue
                dp = minimum_axes(m, axes, q)
                brute = brute_force_minimum_axes(m, axes, q)
                assert (dp is None) == (brute is None), (m, axes, q, dp, brute)
                if dp is not None:
                    assert len(dp) == len(brute)
                    assert rotation_subgroup_order(m, dp) == q
                dp_checks += 1

    sparse = (0, 6, 10, 15)
    chosen = minimum_axes(30, sparse, 30)
    assert chosen == (6, 10, 15)
    assert generated_dihedral_group_order(30, chosen) == 60
    for pair in combinations(sparse, 2):
        assert rotation_subgroup_order(30, pair) != 30
    examples += 1

    full = minimum_axes(12, range(12), 12)
    assert full == (0, 1) and generated_dihedral_group_order(12, full) == 24
    examples += 1

    proper = minimum_axes(30, (0, 5, 10, 15, 20, 25), 6)
    assert proper is not None and len(proper) == 2
    assert rotation_subgroup_order(30, proper) == 6
    examples += 1

    return {
        "dihedral_composition_checks": composition_checks,
        "gcd_formula_vs_group_closure_checks": subgroup_checks,
        "minimum_axis_dp_vs_bruteforce_checks": dp_checks,
        "worked_geometric_examples": examples,
    }


def main() -> None:
    m, axes = 30, (0, 6, 10, 15)
    chosen = minimum_axes(m, axes, m)
    print("m=30, available axes:", axes)
    print("minimum axes for full D_30:", chosen)
    print("generated group order:", generated_dihedral_group_order(m, chosen or ()))
    print("pairwise rotation orders:", {
        pair: rotation_subgroup_order(m, pair) for pair in combinations(axes, 2)
    })
    print("full D_12 from all 12 axes:", minimum_axes(12, range(12), 12))
    print("bounded verification:", verify())


if __name__ == "__main__":
    main()
